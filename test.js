const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html','utf8');
const css = fs.readFileSync('styles.css','utf8');
const js = fs.readFileSync('script.js','utf8');
for(const id of ['main','top','work','approach','background','contact']) assert.match(html,new RegExp('id="'+id+'"'));
for(const repo of ['agent-mcp-gateway','playwright-auto','Advance-Clipboard','lantern','hport']) assert.ok(html.includes('https://github.com/Hiroshimeow/'+repo));
