const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('index.html','utf8');
const css = fs.readFileSync('styles.css','utf8');
const js = fs.readFileSync('script.js','utf8');
for(const id of ['main','top','work','approach','background','contact']) assert.match(html,new RegExp('id="'+id+'"'));
for(const repo of ['agent-mcp-gateway','playwright-auto','Advance-Clipboard','lantern','hport']) assert.ok(html.includes('https://github.com/Hiroshimeow/'+repo));
assert.ok(html.includes('10.1109/IEVC69170.2026.11508619'));
assert.equal((html.match(/class="project"/g)||[]).length,5);
assert.match(html,/name="viewport"/);
assert.match(html,/class="skip-link"/);
assert.match(html,/aria-expanded="false"/);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.match(css,/:focus-visible/);
assert.match(js,/Escape/);
for(const asset of ['styles.css','script.js','favicon.svg','og.png']) assert.ok(fs.existsSync(asset), `Missing ${asset}`);
const favicon = fs.readFileSync('favicon.svg','utf8');
assert.ok(favicon.length > 300, 'Favicon must contain actual artwork');
assert.match(favicon, /<svg[^>]*xmlns="http:\/\/www\.w3\.org\/2000\/svg"/);
assert.match(favicon, /width="64"[^>]*height="64"[^>]*viewBox="0 0 64 64"/);
assert.match(favicon, /<rect\b/);
assert.match(favicon, /<path\b/);
assert.doesNotMatch(favicon, /<svg\s*\/\s*>/);
const png = fs.readFileSync('og.png');
assert.ok(png.length > 15000, 'OG image must be more than an empty/solid-color placeholder');
assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Valid PNG signature');
assert.equal(png.subarray(12,16).toString('ascii'),'IHDR','PNG header');
assert.equal(png.readUInt32BE(16),1200,'OG width');
assert.equal(png.readUInt32BE(20),630,'OG height');
assert.equal(png[24],8,'PNG bit depth');
assert.ok([2,6].includes(png[25]),'OG PNG RGB or RGBA');
assert.equal(png.subarray(png.length-8).toString('hex'),'49454e44ae426082','PNG IEND');
assert.match(html, /<meta property="og:image" content="https:\/\/hcu-lab\.me\/h-lab-portfolio\/og\.png">/);
assert.match(html, /<meta property="og:image:width" content="1200">/);
assert.match(html, /<meta property="og:image:height" content="630">/);
assert.match(html, /<meta property="og:image:type" content="image\/png">/);
assert.match(html, /<meta name="twitter:card" content="summary_large_image">/);
assert.match(html, /<meta name="twitter:image" content="https:\/\/hcu-lab\.me\/h-lab-portfolio\/og\.png">/);
assert.doesNotMatch(html, /og\.svg/);
assert.doesNotMatch(html,/(?:src|href)="\/(?!\/)/);
console.log('PASS: anchors, 5 projects, DOI, metadata, assets, accessibility and responsive contracts');
